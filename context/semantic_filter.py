"""Semantic-only exclusions; structural jobs keep their own source coverage."""

import re
from pathlib import PurePosixPath


def semantic_source_allowed(path: str, content: str = "") -> bool:
    parts = PurePosixPath(path.replace("\\", "/")).parts
    lowered = [part.lower() for part in parts]
    if any(part in {"test", "tests", "__tests__", "spec", "specs", "fixtures",
                    "generated", "__generated__", "gen", "coverage", "dist", "build"}
           for part in lowered[:-1]):
        return False
    name = lowered[-1] if lowered else ""
    if (name.startswith("test_") or name.endswith("_test.py") or
            re.search(r"[._](test|spec)\.[^.]+$", name) or
            name.endswith((".min.js", ".min.css", ".map", ".d.ts", ".pb.go", "_pb2.py"))):
        return False
    header = content[:2048].lower()
    if any(marker in header for marker in ("@generated", "auto-generated", "autogenerated",
                                           "code generated", "do not edit")):
        return False
    if "eicar-standard-antivirus-test-file" in content.lower():
        return False
    return not any(ord(char) < 32 and char not in "\n\r\t\f" for char in content)
