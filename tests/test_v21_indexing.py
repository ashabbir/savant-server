def test_filtered_vector_search_returns_small_repository_even_with_ann_index(source_repo, monkeypatch):
    large = ContextDB.add_repo('large', str(source_repo))
    small = ContextDB.add_repo('small', str(source_repo))
    large_file = ContextDB.insert_file(large['id'], 'a.py', 'python', False, 1, '2026-01-01T00:00:00Z')
    small_file = ContextDB.insert_file(small['id'], 'b.py', 'python', False, 1, '2026-01-01T00:00:00Z')
    ContextDB.insert_chunks_batch(large_file, [(i, 'distractor', [1.0] + [0.0] * 767) for i in range(300)])
    ContextDB.insert_chunk(small_file, 0, 'small repository result', [0.0, 1.0] + [0.0] * 766)
    # Force PostgreSQL to consider the approximate vector index on this small fixture.
    import context.db as context_db
    original = context_db.get_connection
    def ann_connection():
        conn = original()
        with conn.cursor() as cur:
            cur.execute('SET enable_seqscan=off')
        return conn
    monkeypatch.setattr(context_db, 'get_connection', ann_connection)
    rows = ContextDB.vector_search([1.0] + [0.0] * 767, repo_filter='SMALL', limit=5)
    assert len(rows) == 1
    assert rows[0]['repo'] == 'small'


def test_invalid_utf8_is_rejected_instead_of_silently_indexing_partial_source(source_repo):
    (source_repo / 'main.py').write_bytes(b'def calculate(): return 1\n\xff\xfe')
