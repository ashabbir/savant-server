"""Release-contract regressions for independent semantic and structural lifecycles."""
import subprocess
from unittest.mock import Mock

import pytest
from context.db import ContextDB
from context.indexer import Indexer
from db.users import UserDB
from postgres_client import get_connection, release_connection


class Embedder:
    def embed(self, texts):
        return [[0.1] * 768 for _ in texts]


@pytest.fixture
def source_repo(tmp_path, monkeypatch):
    tmp_path = tmp_path / 'source'
    tmp_path.mkdir()
    (tmp_path / 'main.py').write_text('def calculate():\n    return 1\n')
    subprocess.run(['git', 'init', '-q', str(tmp_path)], check=True)
    subprocess.run(['git', '-C', str(tmp_path), 'add', '.'], check=True)
    monkeypatch.setattr(Indexer, '_get_embedder', lambda self: Embedder())
    monkeypatch.setattr('context.indexer._schedule_status_cleanup', lambda _: None)
    return tmp_path


def query(sql, params=()):
    conn = get_connection()
    try:
        with conn.cursor() as cur:
            cur.execute(sql, params)
            rows = cur.fetchall() if cur.description else []
        conn.commit()
        return rows
    finally:
        release_connection(conn)


def test_semantic_rebuild_and_pruning_preserve_structural_artifacts(source_repo):
    indexer = Indexer()
    indexer.generate_ast_for_repository(source_repo, 'isolation')
    before = ContextDB.get_lossless_tree('isolation', 'main.py')
    ast = ContextDB.list_file_ast_nodes('isolation', 'main.py')
    assert before and ast
    indexer.index_repository(source_repo, 'isolation')
    assert ContextDB.get_lossless_tree('isolation', 'main.py') == before
    assert ContextDB.list_file_ast_nodes('isolation', 'main.py') == ast
    (source_repo / 'main.py').unlink()
    indexer.index_repository(source_repo, 'isolation', clear=False)
    assert ContextDB.get_lossless_tree('isolation', 'main.py') == before
    assert ContextDB.list_file_ast_nodes('isolation', 'main.py') == ast
    assert not query('SELECT * FROM ctx_chunks')


def test_structural_refresh_does_not_make_semantic_content_current(source_repo):
    indexer = Indexer()
    indexer.index_repository(source_repo, 'freshness')
    (source_repo / 'main.py').write_text('def calculate():\n    return 999\n')
    indexer.generate_ast_for_repository(source_repo, 'freshness')
    assert ContextDB.get_repo('freshness')['status'] == 'indexed'
    result = indexer.index_repository(source_repo, 'freshness', clear=False)
    assert result['files_indexed'] == 1
    assert '999' in query('SELECT content FROM ctx_chunks')[0]['content']


def test_failed_embedding_is_retried_even_after_structural_refresh(source_repo, monkeypatch):
    indexer = Indexer()
    failing = Mock()
    failing.embed.side_effect = RuntimeError('offline')
    monkeypatch.setattr(indexer, '_get_embedder', lambda: failing)
    assert indexer.index_repository(source_repo, 'retry')['errors'] == 1
    indexer.generate_ast_for_repository(source_repo, 'retry')
    monkeypatch.setattr(indexer, '_get_embedder', lambda: Embedder())
    assert indexer.index_repository(source_repo, 'retry', clear=False)['files_indexed'] == 1


@pytest.mark.parametrize('path,content', [
    ('tests/test_main.py', 'def test_sample(): pass'),
    ('src/main.test.ts', 'function sample() {}'),
    ('src/generated/client.py', 'def generated(): pass'),
    ('client.py', '# Code generated by a tool. DO NOT EDIT.\ndef generated(): pass'),
    ('asset.py', '\x01\x02\x03' * 40),
    ('bad.py', 'X5O!P%@AP[4\\PZX54(P^)7CC)7}$EICAR-STANDARD-ANTIVIRUS-TEST-FILE!$H+H*'),
])
def test_semantic_exclusions_leave_structural_paths_available(source_repo, path, content):
    target = source_repo / path
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content)
    subprocess.run(['git', '-C', str(source_repo), 'add', '.'], check=True)
    Indexer().index_repository(source_repo, 'excluded')
    assert not query('SELECT c.id FROM ctx_chunks c JOIN ctx_files f ON f.id=c.file_id WHERE f.rel_path=%s', (path,))
    Indexer().generate_ast_for_repository(source_repo, 'excluded')
    assert ContextDB.get_lossless_tree('excluded', path) is not None


def test_chunk_batch_keeps_vectors_from_every_insert_page(source_repo):
    repo = ContextDB.add_repo('batch', str(source_repo))
    fid = ContextDB.insert_file(repo['id'], 'main.py', 'python', False, 1, '2026-01-01T00:00:00Z')
    ids = ContextDB.insert_chunks_batch(fid, [(i, str(i), [0.1] * 768) for i in range(251)])
    assert len(ids) == 251
    assert query('SELECT COUNT(*) AS count FROM ctx_vec_chunks')[0]['count'] == 251


